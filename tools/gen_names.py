"""Official GW2 names in en/de/fr/es from the public GW2 API (no key) -> data/gw2-names.tsv.

One line per name that differs between the languages: key <TAB> en <TAB> de <TAB> fr <TAB> es.
Names that are the same in every language are left out (nothing to translate), and so is a second id with the
same names (story copies of a map). Run once per release; --check only compares with the file in the repo.
"""
import json
import sys
import urllib.request
from pathlib import Path

API = "https://api.guildwars2.com/v2/"
LANGS = ("en", "de", "fr", "es")
OUT = Path(__file__).resolve().parent.parent / "data" / "gw2-names.tsv"
INC = OUT.parent.parent / "src" / "core" / "gw2_names.inc"  # compiled in (glossary.cpp): UTF-8, non-ASCII as octal
# Map types a player names in chat: the open world and the WvW maps. Instances are mostly story steps named with
# ordinary words ("Doubt", "Forward", "Silence") – dungeons, raids and fractals go by their abbreviations (terms list).
MAP_TYPES = {"Public", "Center", "RedHome", "BlueHome", "GreenHome", "EdgeOfTheMists"}


def get(path):
    req = urllib.request.Request(API + path, headers={"User-Agent": "GW2Chatlator gen_names"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def fetch(endpoint, lang):
    if endpoint == "maps":  # no ids=all here: pages of 200
        out, page = [], 0
        while True:
            try:
                part = get(f"maps?page={page}&page_size=200&lang={lang}")
            except urllib.error.HTTPError:
                return out
            out += part
            page += 1
    return get(f"{endpoint}?ids=all&lang={lang}")


def collect():
    rows = {}
    for cat, endpoint in (("map", "maps"), ("prof", "professions"), ("spec", "specializations"),
                          ("mount", "mounts/types"), ("wvw", "wvw/objectives")):
        per_lang = {}
        for lang in LANGS:
            for item in fetch(endpoint, lang):
                if cat == "map" and item.get("type") not in MAP_TYPES:
                    continue
                if cat == "wvw" and item.get("type") not in ("Camp", "Tower", "Keep", "Castle"):  # "Altar", "Shrine"
                    continue
                if cat == "spec" and not item.get("elite"):  # core lines are ordinary words ("Fire", "Arms", "Honor")
                    continue
                name = (item.get("name") or "").strip()
                if name:
                    per_lang.setdefault(f"{cat}:{item['id']}", {})[lang] = name
        for key, names in per_lang.items():
            # WvW objectives named after their map ("Garrison" = "Festung von", "- Garnison") are templates, not names
            if any(n.startswith("-") or n.endswith(" von") for n in names.values()):
                continue
            if all(l in names for l in LANGS):
                rows[key] = tuple(names[l] for l in LANGS)
    seen, lines = set(), []
    for key in sorted(rows, key=lambda k: (k.split(":")[0], int(k.split(":")[1]) if k.split(":")[1].isdigit() else 0, k)):
        names = rows[key]
        if len(set(n.casefold() for n in names)) == 1 or names in seen:
            continue
        seen.add(names)
        lines.append("\t".join((key,) + names))
    return lines


def literal(s):
    out = []
    for b in s.encode("utf-8"):
        c = chr(b)
        out.append("\\" + c if c in '"\\' else c if 0x20 <= b < 0x7F and c != "?" else f"\\{b:03o}")
    return '"' + "".join(out) + '"'


def render(lines):
    return ("// Generated by tools/gen_names.py from data/gw2-names.tsv - do not edit; key, en, de, fr, es.\n" +
            "".join("{" + ", ".join(literal(c) for c in l.split("\t")) + "},\n" for l in lines))


def current(path, text):
    return path.exists() and path.read_text(encoding="utf-8").replace("\r\n", "\n") == text


def main():
    head = "# Official GW2 names (GW2 API, public endpoints) - written by tools/gen_names.py, do not edit by hand\n"
    lines = collect()
    text, inc = head + "\n".join(lines) + "\n", render(lines)
    if "--check" in sys.argv:
        same = current(OUT, text) and current(INC, inc)
        print("gen_names: names are current" if same else "gen_names: the API differs - run: python tools/gen_names.py")
        return 0 if same else 1
    OUT.write_text(text, encoding="utf-8", newline="\n")
    INC.write_text(inc, encoding="utf-8", newline="\n")
    print(f"gen_names: {text.count(chr(10)) - 1} names, {len(text.encode('utf-8'))} bytes -> {OUT.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
