"""data/gw2-terms.tsv -> src/core/gw2_terms.inc: the built-in GW2 terms, compiled into the add-on.

Edit the TSV (term <TAB> kind <TAB> meaning), then run this script and build; core_tests compares the two and names
this script when they differ.

  python tools/gen_terms.py          write src/core/gw2_terms.inc (only when it changes)
  python tools/gen_terms.py --check  exit 1 when the .inc does not match the TSV
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
TSV = ROOT / "data" / "gw2-terms.tsv"
INC = ROOT / "src" / "core" / "gw2_terms.inc"
KINDS = {"keep": "TermKind::Keep", "caps": "TermKind::Caps", "word": "TermKind::Word"}
MAX_WORDS = 5  # "Stronghold of the Faithful" – the protection looks this far


def parse(text):
    entries, seen, errors = [], {}, []
    for n, raw in enumerate(text.lstrip("﻿").splitlines(), 1):
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        cols = [c.strip() for c in raw.split("\t")]
        term = " ".join(cols[0].split())
        kind = cols[1] if len(cols) > 1 else ""
        meaning = cols[2] if len(cols) > 2 else ""
        words = term.replace("-", " ").split()
        if kind not in KINDS:
            errors.append(f"line {n}: '{term}' has kind '{kind}' - keep, caps or word")
        elif not words or len(words) > MAX_WORDS:
            errors.append(f"line {n}: '{term}' - one to {MAX_WORDS} words")
        elif len(words) > 1 and kind != "keep":
            errors.append(f"line {n}: '{term}' - several words are a term only as keep")
        elif kind == "caps" and not term.isalnum():
            errors.append(f"line {n}: '{term}' - a caps term is one word of letters and digits")
        key = " ".join(words).casefold().replace("'", "").replace("’", "")
        if key in seen:
            errors.append(f"line {n}: '{term}' is already in line {seen[key]}")
        seen[key] = n
        entries.append((term, kind, meaning))
    return entries, errors


def literal(s):
    out = []
    for ch in s:
        if ch in '\\"':
            out.append("\\" + ch)
        elif 0x20 <= ord(ch) < 0x7F:
            out.append(ch)
        elif ord(ch) <= 0xFFFF:
            out.append(f"\\u{ord(ch):04X}")
        else:
            out.append(f"\\U{ord(ch):08X}")
    return 'L"' + "".join(out) + '"'


def render(entries):
    lines = ["// Generated by tools/gen_terms.py from data/gw2-terms.tsv - edit the TSV, then run the script.\n"]
    for term, kind, meaning in entries:
        lines.append(f"{{{literal(term)}, {KINDS[kind]}, {literal(meaning)}}},\n")
    return "".join(lines)


def main():
    entries, errors = parse(TSV.read_text(encoding="utf-8"))
    if errors:
        print("\n".join(errors))
        return 1
    text = render(entries)
    current = INC.read_text(encoding="utf-8") if INC.exists() else ""
    if "--check" in sys.argv:
        if current != text:
            print(f"{INC.relative_to(ROOT)} does not match {TSV.relative_to(ROOT)} - run: python tools/gen_terms.py")
            return 1
        print(f"ok: {len(entries)} terms")
        return 0
    if current != text:
        INC.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {INC.relative_to(ROOT)}: {len(entries)} terms")
    else:
        print(f"unchanged: {len(entries)} terms")
    return 0


if __name__ == "__main__":
    sys.exit(main())
